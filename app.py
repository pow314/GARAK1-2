def create_25_item_chunks(data_dict, chunk_size=25):
  keys = list(data_dict.keys())
  chunks = {}
  for i in range(0, len(keys), chunk_size):
    sub_keys = keys[i : i + chunk_size]
    start_q = sub_keys[0]
    end_q = sub_keys[-1]
    label = f"📌 {start_q}번 ~ {end_q}번 ({len(sub_keys)}문항)"
    chunks[label] = {k: data_dict[k] for k in sub_keys}
  return chunks


